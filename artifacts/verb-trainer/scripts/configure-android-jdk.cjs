/**
 * Configure Android Studio's project-local Gradle JDK mapping when a usable
 * Java 21 installation is available.
 *
 * Android Studio's default `#GRADLE_LOCAL_JAVA_HOME` setting reads
 * android/.gradle/config.properties. That file is intentionally ignored
 * because the JDK path is machine-specific, so generate it during the normal
 * Capacitor sync instead of shipping an invalid absolute path in the archive.
 */

const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const androidDir = path.join(root, "android");
const configPath = path.join(androidDir, ".gradle", "config.properties");
const javaExecutable = process.platform === "win32" ? "java.exe" : "java";

function isJavaHome(candidate) {
  return Boolean(
    candidate &&
      fs.existsSync(path.join(candidate, "bin", javaExecutable)),
  );
}

function detectJavaHomeFromPath() {
  const result = spawnSync(
    javaExecutable,
    ["-XshowSettings:properties", "-version"],
    { encoding: "utf8" },
  );
  const output = `${result.stdout ?? ""}\n${result.stderr ?? ""}`;

  const match = output.match(/^\s*java\.home\s*=\s*(.+)$/m);
  return match?.[1]?.trim() ?? null;
}

function javaMajorVersion(javaHome) {
  const executable = path.join(javaHome, "bin", javaExecutable);
  const result = spawnSync(executable, ["-version"], { encoding: "utf8" });
  const output = `${result.stdout ?? ""}\n${result.stderr ?? ""}`;

  const match = output.match(/version "(\d+)(?:\.\d+)?/);
  return match ? Number(match[1]) : null;
}

function androidStudioCandidates() {
  const home = os.homedir();

  if (process.platform === "win32") {
    return [
      process.env.LOCALAPPDATA &&
        path.join(process.env.LOCALAPPDATA, "Programs", "Android Studio", "jbr"),
      "C:\\Program Files\\Android\\Android Studio\\jbr",
      "C:\\Program Files\\Android\\Android Studio\\jre",
    ];
  }

  if (process.platform === "darwin") {
    return [
      "/Applications/Android Studio.app/Contents/jbr/Contents/Home",
      path.join(home, "Library", "Application Support", "Google", "AndroidStudio", "jbr"),
    ];
  }

  return [
    "/opt/android-studio/jbr",
    path.join(home, ".local", "share", "Google", "AndroidStudio", "jbr"),
  ];
}

const candidates = [
  process.env.JAVA_HOME,
  process.env.JDK_HOME,
  process.env.STUDIO_JDK,
  detectJavaHomeFromPath(),
  ...androidStudioCandidates(),
].filter(Boolean);

const usableHomes = [...new Set(candidates)]
  .map((candidate) => path.resolve(candidate))
  .filter(isJavaHome);
const javaHome = usableHomes.find((candidate) => javaMajorVersion(candidate) >= 21);

if (!javaHome) {
  const foundVersion = usableHomes
    .map((candidate) => `${candidate} (Java ${javaMajorVersion(candidate) ?? "unknown"})`)
    .join(", ");

  console.warn(
    "No Java 21 installation was found. In Android Studio, set " +
      "Settings > Build, Execution, Deployment > Build Tools > Gradle > " +
      "Gradle JDK to Embedded JDK, then sync again." +
      (foundVersion ? ` Found: ${foundVersion}` : ""),
  );
  process.exit(0);
}

fs.mkdirSync(path.dirname(configPath), { recursive: true });
const escapedJavaHome = javaHome.replaceAll("\\", "\\\\");
const contents =
  "# Generated by configure-android-jdk.cjs; this path is machine-specific.\n" +
  `java.home=${escapedJavaHome}\n`;

const existingContents = fs.existsSync(configPath)
  ? fs.readFileSync(configPath, "utf8")
  : "";

if (existingContents.trim() !== contents.trim()) {
  fs.writeFileSync(configPath, contents, "utf8");
  console.log(`Configured Android Studio Gradle JDK: ${javaHome}`);
} else {
  console.log(`Android Studio Gradle JDK already configured: ${javaHome}`);
}